@pytest.mark.parametrize("scene", SCENES)
def test_the_st_starter_declares_exactly_the_scene_tag_set(scene):
    """Ids, direction and type, one message per tag that is wrong."""
    expected = _fixture(scene)
    hands_off = _commanded(scene)
    located, unlocated = _st(scene)
    by_tag: dict[str, list] = {}
    for row in located:
        by_tag.setdefault(row[5], []).append(row)
    wide = {tag: (name, ty) for name, ty, tag in unlocated}

    problems = []
    for tag_id, (ty, kind) in sorted(expected.items()):
        rows = by_tag.get(tag_id, [])
        if tag_id in hands_off:
            if rows or tag_id in wide:
                problems.append(f"{tag_id} is driven by a motor starter and must not be wired")
            continue
        io = "I" if kind == "input" else "Q"
        if ty == "bit":
            if len(rows) != 1 or rows[0][1:3] != (io, "X") or rows[0][4] != "BOOL":
                problems.append(f"{tag_id} ({ty}/{kind}) should be one BOOL at %{io}X, "
                                f"is {[(r[0], '%' + r[1] + r[2] + r[3], r[4]) for r in rows]}")
            continue
        halves = sorted(rows, key=lambda r: int(r[3]))
        if (len(halves) != 2 or any(r[1:3] != (io, "W") or r[4] != "WORD" for r in halves)
                or not halves[0][0].endswith("Hi") or not halves[1][0].endswith("Lo")
                or int(halves[1][3]) != int(halves[0][3]) + 1):
            problems.append(f"{tag_id} ({ty}/{kind}) should be two consecutive WORDs at "
                            f"%{io}W, high word first; is {[(r[0], '%' + r[1] + r[2] + r[3]) for r in rows]}")
        if wide.get(tag_id, (None, None))[1] != _IEC_TYPE[ty]:
            problems.append(f"{tag_id} ({ty}) should have a {_IEC_TYPE[ty]} variable, "
                            f"has {wide.get(tag_id)}")
    declared = set(by_tag) | set(wide)
    problems += [f"{tag_id} is declared but the scene has no such tag"
                 for tag_id in sorted(declared - set(expected))]
    assert not problems, f"{scene}:\n  " + "\n  ".join(problems)


@pytest.mark.parametrize("scene", SCENES)
async def test_every_st_address_is_the_one_the_sidecar_serves(scene):
    """An address off by one is worse than no starter: it drives the wrong
    device with nothing on either side to say so. So each located variable is
    checked against the driver's real allocation, through OpenPLC's own
    numbering (`updateBuffersIn_MB`: point n of a polled block is %IX(100 +
    n/8).(n mod 8) or %IW(100 + n), counted from the block's Start)."""
    served = await _served(scene)
    config = _mbconfig(scene)
    blocks = {("Q", "X"): ("coils", "Coils", "0x"), ("I", "X"): ("discrete_inputs", "Discrete_Inputs", "1x"),
              ("Q", "W"): ("holding_registers", "Holding_Registers", "4x"),
              ("I", "W"): ("input_registers", "Input_Registers", "3x")}
    located, _ = _st(scene)
    problems = []
    for name, io, width, index, _type, tag_id, label in located:
        block, key, prefix = blocks[(io, width)]
        start = config[f"{key}_Start"]
        if tag_id not in served:
            problems.append(f"{name} is declared for {tag_id}, which the sidecar does not serve")
            continue
        s_block, s_address, s_width = served[tag_id]
        slave = s_address + (1 if name.endswith("Lo") and s_width == 2 else 0)
        n = slave - start
        want = f"{100 + n // 8}.{n % 8}" if width == "X" else f"{100 + n}"
        if s_block != block or index != want:
            problems.append(f"{tag_id}: the sidecar serves it at {s_block}[{slave}], which "
                            f"OpenPLC calls %{io}{width}{want}; {name} is declared at %{io}{width}{index}")
        if label != f"{prefix}{slave}":
            problems.append(f"{tag_id}: {name}'s comment says {label}, the sidecar serves {prefix}{slave}")
    assert not problems, f"{scene}:\n  " + "\n  ".join(problems)


@pytest.mark.parametrize("scene", SCENES)
async def test_mbconfig_polls_every_wired_point_and_no_hands_off_one(scene):
    """Exactly the range the program declares: a size short of it leaves a
    variable that never changes, and a coil block that reaches a starter's
    load writes that tag on every poll -- which the guarded cell fails."""
    served = await _served(scene)
    config = _mbconfig(scene)
    hands_off = _commanded(scene)
    keys = {"coils": "Coils", "discrete_inputs": "Discrete_Inputs",
            "input_registers": "Input_Registers", "holding_registers": "Holding_Registers"}
    problems = []
    for block, key in keys.items():
        used = sorted(a for tid, (b, addr, w) in served.items() if b == block and tid not in hands_off
                      for a in range(addr, addr + w))
        start, size = config[f"{key}_Start"], config[f"{key}_Size"]
        want = (used[0], used[-1] - used[0] + 1) if used else (0, 0)
        if (start, size) != want and not (not used and size == 0):
            problems.append(f"{key}: Start {start} Size {size}, the wired points need {want}")
        for tid in hands_off:
            b, addr, w = served[tid]
            if b == block and size and addr < start + size and addr + w > start:
                problems.append(f"{tid} ({block}[{addr}]) is inside the polled range {start}..{start + size - 1}")
    if config.get("Holding_Registers_Read_Size", 0):
        problems.append("Holding_Registers_Read would shift every %IW after the input registers")
    assert not problems, f"{scene}:\n  " + "\n  ".join(problems)


@pytest.mark.parametrize("scene", SCENES)
def test_the_st_moves_every_32_bit_value_through_both_registers(scene):
    """The declarations can be right and the program still read half a number.
    Every wide input is rebuilt from its own Hi and Lo, with the function for
    its type; every wide output is split into its own Hi and Lo."""
    body = _without_comments(_program(scene))
    located, unlocated = _st(scene)
    kinds = _fixture(scene)
    problems = []
    for name, ty, tag_id in unlocated:
        if tag_id not in kinds:
            problems.append(f"{name} is declared for {tag_id}, which the scene does not have")
            continue
        if kinds[tag_id][1] == "input":
            fn = "FF_WORDS_TO_REAL" if ty == "REAL" else "FF_WORDS_TO_DINT"
            pattern = rf"^\s*{name}\s*:=\s*{fn}\(HI\s*:=\s*{name}Hi,\s*LO\s*:=\s*{name}Lo\);"
        else:
            fn = "FF_REAL_TO_DWORD" if ty == "REAL" else "DINT_TO_DWORD"
            pattern = (rf"^\s*Raw32\s*:=\s*{fn}\({name}\);\s*\n"
                       rf"\s*{name}Hi\s*:=\s*DWORD_TO_WORD\(SHR\(IN\s*:=\s*Raw32,\s*N\s*:=\s*16\)\);\s*\n"
                       rf"\s*{name}Lo\s*:=\s*DWORD_TO_WORD\(Raw32\);")
        if not re.search(pattern, body, re.M):
            problems.append(f"{tag_id}: no {fn} line moving {name} through {name}Hi/{name}Lo")
    assert not problems, f"{scene}:\n  " + "\n  ".join(problems)


@pytest.mark.parametrize("scene", SCENES)
def test_the_logic_is_left_to_the_student(scene):
    """No solutions (IP-10). Section 2 of the ST and the FB's body are
    comments and nothing else."""
    st = _program(scene)
    section = re.search(r"2\. Your program(.*?)=====\s*3\.", st, re.S)
    assert section, f"{scene}: the .st has no section 2"
    leftover = _without_comments("(*" + section.group(1) + "*)").strip()
    assert not leftover, f"{scene}: the .st's logic section contains {leftover!r}"

    scl = _read(EXAMPLES / "tia" / scene / f"{_stem(scene)}.scl")
    fb = re.search(r"^FUNCTION_BLOCK.*?^BEGIN$(.*?)^END_FUNCTION_BLOCK", scl, re.S | re.M)
    assert fb, f"{scene}: no FUNCTION_BLOCK body in the .scl"
    code = [line for line in fb.group(1).splitlines()
            if line.strip() and not line.strip().startswith("//")]
    assert not code, f"{scene}: the FB body contains {code}"


_FIRST_POLL = "**Every input reads FALSE until OpenPLC's first poll returns.**"


@pytest.mark.parametrize("scene", SCENES)
def test_an_openplc_starter_with_an_estop_warns_about_the_first_scans(scene):
    """IP-41, AGENTS.md gotcha 25. OpenPLC scans before its first Modbus poll
    returns and reads every input FALSE until then, so a normally closed
    E-stop looks struck and a trip latched on `NOT PanelEstop` trips itself on
    every start. The guide's program found that on a real OpenPLC; a student
    starting from a starter must be told before they find it the same way.
    Whether the scene has an E-stop comes from the engine's tag set, not the
    generator."""
    if "panel.estop" not in _fixture(scene):
        pytest.skip(f"{scene} has no panel.estop")
    readme = _read(EXAMPLES / "openplc" / scene / "README.md")
    start = readme.find("- " + _FIRST_POLL)
    assert start >= 0, f"{scene}: the OpenPLC README does not warn that the first scans read FALSE"
    bullet = re.split(r"\n(?=- |#)", readme[start:])[0]
    bullet = " ".join(bullet.split())
    for needle in ("`panel.estop`", "EstopSeen", "NOT PanelEstop", "docs/OPENPLC.md"):
        assert needle in bullet, f"{scene}: the first-scan warning does not mention {needle}"
    # Every other normally closed input the README's own I/O table lists.
    closed = re.findall(r"^\| `([\w.]+)` \| PLC reads \| bit \|[^\n]*normally closed", readme, re.M)
    assert "panel.estop" in closed, f"{scene}: the I/O table does not call panel.estop normally closed"
    for tag in closed:
        assert f"`{tag}`" in bullet, f"{scene}: the first-scan warning leaves out {tag}, normally closed"

    section = re.search(r"2\. Your program(.*?)=====\s*3\.", _program(scene), re.S)
    assert section, f"{scene}: the .st has no section 2"
    text = " ".join(section.group(1).split())
    assert "IF PanelEstop THEN EstopSeen := TRUE; END_IF;" in text, (
        f"{scene}: the .st's section 2 does not show the EstopSeen pattern")
    assert "EstopSeen AND NOT PanelEstop" in text, f"{scene}: the .st does not arm the trip on EstopSeen"


