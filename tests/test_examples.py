@pytest.mark.parametrize("scene", SCENES)
def test_the_scl_db_declares_exactly_the_scene_tag_set(scene):
    expected = _fixture(scene)
    hands_off = _commanded(scene)
    members = _scl_members(scene)
    problems = []
    seen = {}
    for member, s7, tag_id, direction in members:
        if tag_id in seen:
            problems.append(f"{tag_id} is declared twice")
        seen[tag_id] = (s7, direction)
    for tag_id, (ty, kind) in sorted(expected.items()):
        if tag_id in hands_off:
            if tag_id in seen:
                problems.append(f"{tag_id} is driven by a motor starter and must not be in FF_IO")
            continue
        want = (_S7_TYPE[ty], "PLC writes" if kind == "output" else "PLC reads")
        if seen.get(tag_id) != want:
            problems.append(f"{tag_id} ({ty}/{kind}) should be {want}, is {seen.get(tag_id)}")
    problems += [f"{tid} is in FF_IO but the scene has no such tag" for tid in sorted(set(seen) - set(expected))]
    assert not problems, f"{scene}:\n  " + "\n  ".join(problems)


@pytest.mark.parametrize("scene", SCENES)
def test_the_opcua_and_plcsim_mappings_name_the_db_members(scene):
    """The mapping is what the driver exchanges. A member it names that the DB
    does not have is `bad_node`; a tag it leaves out is never exchanged."""
    members = {tag_id: member for member, _s7, tag_id, _d in _scl_members(scene)}
    opcua = _mapping(scene, "opcua_mapping.json")
    plcsim = _mapping(scene, "plcsim_mapping.json")
    assert set(opcua) == set(members), f"{scene}: opcua keys {sorted(set(opcua) ^ set(members))}"
    assert set(plcsim) == set(members), f"{scene}: plcsim keys {sorted(set(plcsim) ^ set(members))}"
    for tag_id, member in members.items():
        assert opcua[tag_id] == f'ns=3;s="FF_IO"."{member}"', (scene, tag_id, opcua[tag_id])
        assert plcsim[tag_id] == f"FF_IO.{member}", (scene, tag_id, plcsim[tag_id])


def _s7_offsets(members) -> dict[str, tuple[int, int | None, int]]:
    """Standard-access layout, from the SCL member order: `{tag: (byte, bit or
    None, size)}`. Bools pack eight to a byte from bit 0; a 4-byte DInt or
    Real starts on the next even byte. The same rules produced FF_IO's
    verified layout (examples/snap7_mapping.json: eight Bools, DBD2, DBD6)."""
    out, byte, bit = {}, 0, 0
    for _member, s7, tag_id, _d in members:
        if s7 == "Bool":
            out[tag_id] = (byte, bit, 1)
            bit += 1
            if bit == 8:
                byte, bit = byte + 1, 0
        else:
            if bit:
                byte, bit = byte + 1, 0
            if byte % 2:
                byte += 1
            out[tag_id] = (byte, None, 4)
            byte += 4
    return out


def test_the_s7_layout_rules_reproduce_the_verified_ff_io():
    """The layout function above is only an authority if it gets the one DB
    that was checked against a live CPU right."""
    doc = [("ConveyorRotate", "Bool", "conveyor.rotate", ""), ("EmitterEmit", "Bool", "emitter.emit", ""),
           ("PusherExtend", "Bool", "pusher.extend", ""), ("StackLightGreen", "Bool", "stack_light.green", ""),
           ("SensorLow", "Bool", "sensor_low.detect", ""), ("SensorHigh", "Bool", "sensor_high.detect", ""),
           ("PusherExtended", "Bool", "pusher.extended", ""), ("PusherRetracted", "Bool", "pusher.retracted", ""),
           ("CounterTall", "DInt", "counter.tall", ""), ("CounterShort", "DInt", "counter.short", "")]
    verified = json.loads(_read(EXAMPLES / "snap7_mapping.json"))
    for tag_id, (byte, bit, _size) in _s7_offsets(doc).items():
        assert verified[tag_id] == (f"DBX{byte}.{bit}" if bit is not None else f"DBD{byte}")


@pytest.mark.parametrize("scene", SCENES)
def test_the_snap7_offsets_follow_the_db_and_never_mix_directions(scene):
    members = _scl_members(scene)
    snap7 = _mapping(scene, "snap7_mapping.json")
    offsets = _s7_offsets(members)
    assert set(snap7) == set(offsets), f"{scene}: snap7 keys {sorted(set(snap7) ^ set(offsets))}"
    owner: dict[int, set[str]] = {}
    for _member, _s7, tag_id, direction in members:
        byte, bit, size = offsets[tag_id]
        want = f"DBX{byte}.{bit}" if bit is not None else f"DBD{byte}"
        assert snap7[tag_id] == want, f"{scene}: {tag_id} is at {want} in the DB, mapped to {snap7[tag_id]}"
        for b in range(byte, byte + size):
            owner.setdefault(b, set()).add(direction)
    shared = sorted(b for b, dirs in owner.items() if len(dirs) > 1)
    assert not shared, (f"{scene}: bytes {shared} hold both PLC- and simulator-written "
                        f"members; snap7 would read-modify-write the PLC's bits (gotcha 19d)")


