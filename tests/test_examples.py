"""The starter programs in `examples/` against the scenes they are for (IP-10).

Every graded scene ships an OpenPLC starter (`examples/openplc/<scene>/`) and a
TIA Portal starter (`examples/tia/<scene>/`): I/O declared, logic empty. They
are generated by `tools/gen_starters.py`, and a starter is a promise a student
builds on without being able to check it -- Modbus carries no tag names, and a
DB member nobody maps is simply never exchanged. So this file reads the
*committed files* the way a student's toolchain would and holds them to three
authorities that do not come from the generator:

* the tag set the engine registers for the scene,
  `engine/fixtures/scene_tag_sets.json` (which `--self-test=scenes` holds the
  engine to, and `test_grade_templates.py` holds the grader to): every tag
  declared, with the right direction and type, and nothing else;
* the Modbus map the sidecar's own `modbus-tcp` driver serves for that tag
  set: every located address in every `.st`, and every size in every
  `mbconfig.cfg`;
* S7's standard-access layout rules, re-derived here from the SCL source's own
  member order, for every offset in every `snap7_mapping.json`.

And then that a fresh run of the generator reproduces every file, so a scene
that changes under a committed starter fails here rather than in a classroom.

`FACTORYFORGE_TAG_FIXTURE` points the whole file (and the generator) at a
different fixture, which is how a renamed tag is shown to fail it.
"""

from __future__ import annotations

import importlib.util
import json
import os
import re
import sys
from pathlib import Path

import pytest

from factoryforge_sidecar import drivers
from factoryforge_sidecar.grading import registry
from factoryforge_sidecar.tags import Tag, TagTable

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"
TEMPLATES = ROOT / "engine" / "templates"
FIXTURE = Path(os.environ.get("FACTORYFORGE_TAG_FIXTURE")
               or ROOT / "engine" / "fixtures" / "scene_tag_sets.json")

SCENES = sorted(registry.rubrics())

_IEC_TYPE = {"bit": "BOOL", "int": "DINT", "float": "REAL"}
_S7_TYPE = {"bit": "Bool", "int": "DInt", "float": "Real"}


def _gen():
    """`tools/gen_starters.py`, imported by path (tools/ is not a package).
    Registered in sys.modules first: its dataclasses look their module up."""
    if "gen_starters" not in sys.modules:
        spec = importlib.util.spec_from_file_location("gen_starters", ROOT / "tools" / "gen_starters.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules["gen_starters"] = module
        spec.loader.exec_module(module)
    return sys.modules["gen_starters"]


def _read(path: Path) -> str:
    # git on Windows checks these out with CRLF; the content is what matters.
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _stem(scene: str) -> str:
    return scene.replace("-", "_")


# --- the authorities ---------------------------------------------------------

def _fixture(scene: str) -> dict[str, tuple[str, str]]:
    """`{tag id: (type, kind)}` the engine registers for *scene*."""
    tags = json.loads(FIXTURE.read_text(encoding="utf-8"))["scenes"][scene]
    return {t["id"]: (t["type"], t["kind"]) for t in tags}


def _commanded(scene: str) -> set[str]:
    """Tags a part in the template drives itself, which the program must never
    write: a motor starter's `load_tag`. Read from the template here rather
    than taken from the generator, so the exception is not self-certified."""
    manifest = {e["id"]: e for e in json.loads(
        (TEMPLATES / "manifest.json").read_text(encoding="utf-8"))}
    path = manifest[scene]["path"]
    if not path:
        return set()
    data = json.loads((TEMPLATES / path.removeprefix("res://templates/")).read_text(encoding="utf-8"))
    return {p["properties"]["load_tag"] for p in data["parts"]
            if p["type"] == "MotorStarter" and p.get("properties", {}).get("load_tag")}


class _SilentBus:
    def on_describe(self, _handler) -> None:
        pass

    on_update = on_disconnect = on_describe

    async def status(self, *args, **kwargs) -> None:
        pass


async def _served(scene: str) -> dict[str, tuple[str, int, int]]:
    """What `modbus-tcp` really serves for this tag set on a fresh sidecar."""
    table = TagTable([Tag(tid, tid, ty, kind) for tid, (ty, kind) in _fixture(scene).items()])
    driver = drivers.create("modbus-tcp", _SilentBus(), port=0)
    await driver.rebuild(scene, 1, table)
    return {m.tag_id: (m.block, m.address, m.width) for m in driver._by_tag.values()}


# --- reading the starters as a toolchain would -------------------------------

_LOCATED = re.compile(
    r"^\s*(\w+)\s+AT\s+%([IQ])([XW])([\d.]+)\s*:\s*(\w+)\s*;\s*\(\*\s*(\S+)\s+(\dx\d+)", re.M)
_UNLOCATED = re.compile(r"^\s*(\w+)\s*:\s*(DINT|REAL)\s*;\s*\(\*\s*(\S+)", re.M)


def _program(scene: str) -> str:
    text = _read(EXAMPLES / "openplc" / scene / f"{_stem(scene)}.st")
    match = re.search(r"^PROGRAM\s+\w+\s*$(.*?)^END_PROGRAM", text, re.S | re.M)
    assert match, f"{scene}: no PROGRAM ... END_PROGRAM in the .st"
    return match.group(1)


def _st(scene: str):
    """`(located, unlocated)`: `[(name, 'I'|'Q', 'X'|'W', index, type, tag, label)]`
    and `[(name, type, tag)]`, from the PROGRAM's declarations only."""
    body = _program(scene)
    return _LOCATED.findall(body), _UNLOCATED.findall(body)


def _without_comments(text: str) -> str:
    return re.sub(r"\(\*.*?\*\)", " ", text, flags=re.S)


def _mbconfig(scene: str) -> dict[str, int]:
    text = _read(EXAMPLES / "openplc" / scene / "mbconfig.cfg")
    return {key: int(value) for key, value in re.findall(r'^device0\.(\w+)\s*=\s*"(\d+)"', text, re.M)}


_SCL_MEMBER = re.compile(
    r"^\s*(\w+)\s*:\s*(Bool|DInt|Real)\s*;\s*//\s*(\S+)\s+\((PLC writes|PLC reads)\)", re.M)


def _scl_members(scene: str) -> list[tuple[str, str, str, str]]:
    """`[(member, S7 type, tag id, direction)]` in declaration order."""
    text = _read(EXAMPLES / "tia" / scene / f"{_stem(scene)}.scl")
    db = re.search(r'^DATA_BLOCK "FF_IO"(.*?)^END_DATA_BLOCK', text, re.S | re.M)
    assert db, f"{scene}: no DATA_BLOCK \"FF_IO\" in the .scl"
    assert "S7_Optimized_Access := 'FALSE'" in db.group(1), (
        f"{scene}: FF_IO must be a standard-access DB, or snap7 has no offsets to use")
    return _SCL_MEMBER.findall(db.group(1))


def _mapping(scene: str, name: str) -> dict[str, str]:
    data = json.loads(_read(EXAMPLES / "tia" / scene / name))
    return {k: v for k, v in data.items() if not k.startswith("_")}


